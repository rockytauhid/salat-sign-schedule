package com.salatsign.tv.quran

import com.salatsign.tv.data.model.AppLanguage
import com.salatsign.tv.data.model.QuranTextEntry
import com.salatsign.tv.engine.JsonQuranVerseRepository
import kotlinx.serialization.builtins.MapSerializer
import kotlinx.serialization.builtins.serializer
import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Verifies the shipped offline Quran JSON assets generated by tools/build_quran_data.py:
 * (a) every reference in tools/verse-list.txt exists in every shipped data file,
 * (b) every Arabic text is non-empty and contains only Arabic-script characters, Quranic marks, and spaces,
 * (c) zero duplicate keys in any JSON file,
 * (d) JSON round-trips character-for-character without change,
 * (e) ATTRIBUTION.md contains the required upstream notices.
 */
class QuranAssetIntegrityTest {

    private fun repoRoot(): File {
        val cwd = File(System.getProperty("user.dir") ?: ".")
        return if (File(cwd, "tools/verse-list.txt").exists()) cwd else cwd.parentFile!!
    }

    private fun extractTopLevelJsonKeys(jsonText: String): List<String> {
        // Every top-level entry in our indented assets is `"surah:ayah": {` or `"surah": {`
        val regex = Regex("""^\s{2}"([^"]+)"\s*:\s*\{""", RegexOption.MULTILINE)
        return regex.findAll(jsonText).map { it.groupValues[1] }.toList()
    }

    private fun isAllowedArabicCodePoint(cp: Int): Boolean {
        return cp == 0x0020 ||              // Space
            cp in 0x0600..0x06FF ||       // Arabic block (letters, harakat, Quranic annotation signs)
            cp in 0x0750..0x077F ||       // Arabic Supplement
            cp in 0x08A0..0x08FF ||       // Arabic Extended-A
            cp in 0xFB50..0xFDFF ||       // Arabic Presentation Forms-A
            cp in 0xFE70..0xFEFF          // Arabic Presentation Forms-B
    }

    @Test
    fun bundledQuranAssets_matchCanonicalVerseListAndIntegrityRules() {
        val root = repoRoot()
        val verseListFile = File(root, "tools/verse-list.txt")
        val assetsDir = File(root, "core-tv-ui/src/main/assets/quran")

        val canonicalRefs = verseListFile.readLines(Charsets.UTF_8)
            .map { it.trim() }
            .filter { it.isNotEmpty() && !it.startsWith("#") }
        assertEquals("Expected 63 canonical verses", 63, canonicalRefs.size)
        assertEquals("Canonical verse list must have no duplicates", 63, canonicalRefs.toSet().size)

        val arJson = File(assetsDir, "verses_ar.json").readText(Charsets.UTF_8)
        val enJson = File(assetsDir, "translations_en.json").readText(Charsets.UTF_8)
        val idJson = File(assetsDir, "translations_id.json").readText(Charsets.UTF_8)
        val surahsJson = File(assetsDir, "surahs.json").readText(Charsets.UTF_8)

        // (c) Zero duplicate keys in raw JSON files
        for ((name, raw) in listOf("verses_ar.json" to arJson, "translations_en.json" to enJson, "translations_id.json" to idJson)) {
            val keys = extractTopLevelJsonKeys(raw)
            assertEquals("$name should have 63 keys", 63, keys.size)
            assertEquals("$name has duplicate keys", 63, keys.toSet().size)
            assertEquals("$name keys must match canonical verse-list.txt", canonicalRefs.toSet(), keys.toSet())
        }

        // (a) & (b) Repository loads all 63 with valid non-empty Arabic & translations
        val repo = JsonQuranVerseRepository(arJson, enJson, idJson, surahsJson)
        assertEquals(63, repo.allReferences().size)
        for (ref in canonicalRefs) {
            val enVerse = repo.getVerse(ref, AppLanguage.EN)
            val idVerse = repo.getVerse(ref, AppLanguage.ID)
            val arLangVerse = repo.getVerse(ref, AppLanguage.AR)

            assertNotNull("Missing EN verse $ref", enVerse)
            assertNotNull("Missing ID verse $ref", idVerse)
            assertNotNull("Missing AR-lang verse $ref", arLangVerse)

            assertTrue("Empty Arabic text for $ref", enVerse!!.arabicText.isNotEmpty())
            assertTrue("Empty EN translation for $ref", enVerse.translationText.isNotEmpty())
            assertTrue("Empty ID translation for $ref", idVerse!!.translationText.isNotEmpty())
            assertEquals("Arabic app language must show English translation for $ref", enVerse.translationText, arLangVerse!!.translationText)
            assertFalse("Missing surah transliteration for $ref", enVerse.surahTransliteration.isBlank())

            // Verify every Arabic codepoint is strictly within Arabic/Quranic Unicode blocks or space
            enVerse.arabicText.codePoints().forEach { cp ->
                assertTrue(
                    "Unexpected codepoint U+${cp.toString(16).uppercase()} in Arabic verse $ref",
                    isAllowedArabicCodePoint(cp)
                )
            }
        }

        // (d) JSON round-trip preserves exact strings with zero modification
        val serializer = MapSerializer(String.serializer(), QuranTextEntry.serializer())
        val jsonCodec = Json { prettyPrint = false }
        for (raw in listOf(arJson, enJson, idJson)) {
            val firstPass = jsonCodec.decodeFromString(serializer, raw)
            val reEncoded = jsonCodec.encodeToString(serializer, firstPass)
            val secondPass = jsonCodec.decodeFromString(serializer, reEncoded)
            assertEquals("JSON round-trip altered verse text", firstPass, secondPass)
        }

        // (e) ATTRIBUTION.md contains mandatory notices
        val attribution = File(assetsDir, "ATTRIBUTION.md").readText(Charsets.UTF_8)
        assertTrue(attribution.contains("Tanzil.net"))
        assertTrue(attribution.contains("http://tanzil.net"))
        assertTrue(attribution.contains("Saheeh International"))
        assertTrue(attribution.contains("Kementerian Agama Republik Indonesia"))
    }
}
